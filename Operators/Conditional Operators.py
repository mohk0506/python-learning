# Conditional operators problem

print(a>4)   # a is greater then 4 Output: True
print(a<4)   # a is less then 4  Output: False
print(a<=4)  # a is less then or equal to 4 Output: False
print(a>=4)  # a is greater then or equal to 4 Output: True
print(a==4)  # Is a equal to 4? Output: False
print(a==34) # Is a equal to 34? Output: True
print(a!=34) # Is a not equal to 34? Output: False

